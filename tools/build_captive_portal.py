"""Regenerate components/captive_portal/captive_index.h from portal.html.

Run after editing portal.html:  python3 esphome/tools/build_captive_portal.py
The other files in components/captive_portal/ are unmodified copies of ESPHome's
built-in component; re-copy them when upgrading ESPHome (version noted below).
"""
import gzip
import pathlib
import re

ESPHOME_VERSION = "2026.10.2"
DIR = pathlib.Path(__file__).resolve().parent.parent / "components" / "captive_portal"

html = (DIR / "portal.html").read_text(encoding="utf-8")
# Light minification: drop indentation and blank lines.
html = "\n".join(line.strip() for line in html.splitlines() if line.strip())
data = gzip.compress(html.encode("utf-8"), compresslevel=9, mtime=0)

rows = [
    "    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 19]) + ","
    for i in range(0, len(data), 19)
]
header = f"""#pragma once
// Generated by esphome/tools/build_captive_portal.py from portal.html - do not edit.
// Based on ESPHome {ESPHOME_VERSION} captive_portal.

#include "esphome/core/hal.h"

namespace esphome::captive_portal {{

#ifndef USE_CAPTIVE_PORTAL_GZIP
#error "Custom captive portal page only supports 'compression: gzip' (the default)"
#endif

constexpr uint8_t INDEX_GZ[] PROGMEM = {{
{chr(10).join(rows)}
}};

}}  // namespace esphome::captive_portal
"""
(DIR / "captive_index.h").write_text(header)
print(f"captive_index.h: {len(html)} bytes HTML -> {len(data)} bytes gzip")
